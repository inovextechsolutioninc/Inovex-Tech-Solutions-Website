import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import Anthropic from '@anthropic-ai/sdk';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Initialize Claude (Anthropic API)
const anthropic = new Anthropic({
  apiKey: process.env.ANTHROPIC_API_KEY || 'sk-placeholder-key', 
});

const TOPICS = [
  "The ROI of AI Automation in B2B SaaS",
  "Replacing traditional chatbots with RAG",
  "Agentic SEO: How AI searches the web in 2026",
  "Automating CRM data entry with Claude 3.5"
];

async function runGEOContentAgent() {
  console.log("🤖 [GEO Content Agent] Waking up...");
  
  if (!process.env.ANTHROPIC_API_KEY) {
    console.log("⚠️ No ANTHROPIC_API_KEY found. Running in simulation mode.");
  }

  const topic = TOPICS[Math.floor(Math.random() * TOPICS.length)];
  console.log(`🧠 [GEO Content Agent] Researching and drafting: "${topic}"`);

  let articleData;

  try {
    if (process.env.ANTHROPIC_API_KEY) {
      // Real Call to Claude 3.5 Sonnet
      const response = await anthropic.messages.create({
        model: "claude-3-5-sonnet-20240620",
        max_tokens: 2000,
        system: "You are an elite technical SEO copywriter for Inovex Tech Solutions. Output ONLY raw JSON matching this schema: { title, slug, date, author, excerpt, htmlContent }.",
        messages: [{ role: "user", content: `Write a comprehensive, highly technical 1000-word blog post about "${topic}". Use HTML formatting for the htmlContent field.` }]
      });
      articleData = JSON.parse(response.content[0].text);
    } else {
      // Simulated generation if no key is provided yet
      articleData = {
        title: topic,
        slug: topic.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
        date: new Date().toISOString().split('T')[0],
        author: "Claude 3.5 Autonomous Agent",
        excerpt: `An in-depth analysis on how ${topic.toLowerCase()} is shifting the enterprise landscape.`,
        htmlContent: `<h2>Understanding ${topic}</h2><p>This article was autonomously generated by the Inovex Tech GEO Agent pipeline.</p>`
      };
    }

    // Save the file
    const contentDir = path.join(process.cwd(), 'src', 'content', 'articles');
    if (!fs.existsSync(contentDir)) fs.mkdirSync(contentDir, { recursive: true });
    
    const filePath = path.join(contentDir, `${articleData.slug}.json`);
    fs.writeFileSync(filePath, JSON.stringify(articleData, null, 2));
    
    console.log(`✅ [GEO Content Agent] Successfully published to ${filePath}`);

  } catch (error) {
    console.error("❌ [GEO Content Agent] Failed:", error.message);
  }
}

runGEOContentAgent();
